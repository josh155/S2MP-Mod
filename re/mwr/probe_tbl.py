import ida_bytes, json
out = {}
for off in (0x00, 0x08, 0x10, 0x18, 0x20, 0x28, 0x30, 0x38, 0x40, 0x48, 0x50, 0x58, 0x60, 0x68):
    a = 0x12D4D00 + off
    out["+0x%02X" % off] = {"q": "0x%X" % ida_bytes.get_qword(a),
                            "d": ida_bytes.get_dword(a)}
print(json.dumps(out, indent=0))
